# ---------------------------------------------------------------- Lodica (Electron browser)
def apply_lodica(c: dict[str, str]) -> None:
    f = CFG / "Lodica" / "prefs.json"
    if not f.exists():
        return
    try:
        data = json.loads(f.read_text())
    except (OSError, ValueError):
        return
    want = {"bg": c["bg"], "text": c["fg"], "accent": c["accent"], "accent2": c["accent2"]}
    cur = data.get("customTheme") or {}
    if data.get("theme") == "custom" and all(cur.get(k) == v for k, v in want.items()):
        return
    data["theme"] = "custom"
    data["customTheme"] = {**want, "at": int(__import__("time").time() * 1000)}
    tmp = f.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(data, separators=(",", ":")))
    tmp.replace(f)


# ---------------------------------------------------------------- KDE / Qt apps (Dolphin, Kate, Okular, ...)
def kde_rgb(c: str) -> str:
    return ",".join(str(x) for x in rgb(c))


def apply_kde(c: dict[str, str], name: str) -> None:
    if not (CFG / "kdeglobals").exists():      # no KDE app has ever run here
        return
    bg, fg, ac, line = c["bg"], c["fg"], c["accent"], c["line"]
    base, alt, muted = c["bg"], c["surface"], mix(bg, fg, 0.5)
    on_ac = readable(ac, bg)
    win = mix(bg, "#000000", 0.12) if lum(bg) < 0.5 else mix(bg, "#000000", 0.05)

    def sect(sec: str, back: str, alt_back: str, front: str = fg) -> str:
        return f"""[Colors:{sec}]
BackgroundNormal={kde_rgb(back)}
BackgroundAlternate={kde_rgb(alt_back)}
ForegroundNormal={kde_rgb(front)}
ForegroundInactive={kde_rgb(muted)}
ForegroundActive={kde_rgb(ac)}
ForegroundLink={kde_rgb(c['accent2'])}
ForegroundVisited={kde_rgb(muted)}
ForegroundNegative={kde_rgb('#e5534b')}
ForegroundNeutral={kde_rgb('#e0a030')}
ForegroundPositive={kde_rgb('#57ab5a')}
DecorationFocus={kde_rgb(ac)}
DecorationHover={kde_rgb(ac)}

"""
    sel = f"""[Colors:Selection]
BackgroundNormal={kde_rgb(ac)}
BackgroundAlternate={kde_rgb(mix(ac, bg, 0.2))}
ForegroundNormal={kde_rgb(on_ac)}
ForegroundInactive={kde_rgb(on_ac)}
ForegroundActive={kde_rgb(on_ac)}
ForegroundLink={kde_rgb(on_ac)}
ForegroundVisited={kde_rgb(on_ac)}
ForegroundNegative={kde_rgb(on_ac)}
ForegroundNeutral={kde_rgb(on_ac)}
ForegroundPositive={kde_rgb(on_ac)}
DecorationFocus={kde_rgb(ac)}
DecorationHover={kde_rgb(ac)}

"""
    cur_name = ""
    kg = CFG / "kdeglobals"
    if kg.exists():
        m = re.search(r"^ColorScheme=(\S+)", kg.read_text(), re.M)
        cur_name = m.group(1) if m else ""
    # plasma-apply-colorscheme ignores a scheme that is already active, so alternate between two names
    new = "HearthshellB" if cur_name == "HearthshellA" else "HearthshellA"
    text = (sect("View", base, alt) + sect("Window", win, mix(win, fg, 0.06)) + sect("Button", alt, mix(alt, fg, 0.06))
            + sect("Tooltip", win, alt) + sect("Complementary", win, alt) + sect("Header", win, alt) + sel
            + f"[General]\nColorScheme={new}\nName={new}\n\n[KDE]\ncontrastSlider=0\n\n"
            + f"[WM]\nactiveBackground={kde_rgb(win)}\nactiveForeground={kde_rgb(fg)}\n"
            + f"inactiveBackground={kde_rgb(win)}\ninactiveForeground={kde_rgb(muted)}\n")
    d = HOME / ".local" / "share" / "color-schemes"
    write(d / f"{new}.colors", text)
    other = d / ("HearthshellA.colors" if new == "HearthshellB" else "HearthshellB.colors")
    if not other.exists():
        write(other, text.replace(new, "HearthshellA" if new == "HearthshellB" else "HearthshellB"))
    run("plasma-apply-colorscheme", new)


# ---------------------------------------------------------------- micro editor
def apply_micro(t: dict[str, Any], c: dict[str, str]) -> None:
    d = CFG / "micro"
    if not d.is_dir():
        return
    tm = t["term"]
    bg, fg, ac = c["bg"], c["fg"], c["accent"]
    surf, muted = c["surface"], mix(bg, fg, 0.45)

    def L(n: str, f: str, b: str = "", extra: str = "") -> str:
        return f'color-link {n} "{extra}{f},{b}"' if b else f'color-link {n} "{extra}{f}"'

    lines = [
        L("default", fg, bg), L("comment", muted, "", "italic "), L("constant", tm["yellow"]), L("constant.string", tm["green"]),
        L("constant.number", tm["magenta"]), L("identifier", tm["blue"]), L("statement", tm["red"]), L("symbol", c["accent2"]),
        L("preproc", tm["magenta"]), L("type", tm["yellow"]), L("special", tm["cyan"]), L("ignore", muted), L("error", tm["red"], bg),
        L("todo", ac, bg, "bold "), L("underlined", c["accent2"], "", "underline "), L("statusline", fg, surf),
        L("tabbar", fg, surf), L("indent-char", muted, bg), L("line-number", muted, bg), L("current-line-number", ac, bg),
        L("diff-added", tm["green"]), L("diff-modified", tm["yellow"]), L("diff-deleted", tm["red"]),
        L("gutter-error", tm["red"], bg), L("gutter-warning", tm["yellow"], bg), L("cursor-line", fg, surf), L("color-column", fg, surf),
        L("selection", bg, ac),
    ]
    write(d / "colorschemes" / "hearthshell.micro", "\n".join(lines) + "\n")
    settings = d / "settings.json"
    try:
        data = json.loads(settings.read_text()) if settings.exists() else {}
    except (OSError, ValueError):
        return
    if data.get("colorscheme") != "hearthshell":
        data["colorscheme"] = "hearthshell"
        write(settings, json.dumps(data, indent=4) + "\n")


# ---------------------------------------------------------------- cava
CAVA_BLOCK = re.compile(rf"# >>> {MARK}\n(.*?)# <<< {MARK}\n", re.S)
CAVA_ACTIVE = re.compile(r"^(?:gradient|gradient_count|gradient_color_\d+)\s*=.*\n", re.M)


def cava_split(text: str) -> tuple[str, list[str]]:
    """The config without our block, and the user's own lines that block had parked."""
    m = CAVA_BLOCK.search(text)
    if not m:
        return text, []
    parked = [ln[len("#was# "):] for ln in m.group(1).splitlines() if ln.startswith("#was# ")]
    head, tail = text[:m.start()], text[m.end():]
    if m.group(1).startswith("[color]"):          # we appended the whole section: take the blank line before it too
        head = head.rstrip("\n") + "\n" if head.strip() else ""
    return head + tail, parked


def apply_cava(c: dict[str, str]) -> None:
    f = CFG / "cava" / "config"
    if not f.exists():
        return
    cols = [mix(c["accent"], c["bg"], 0.35), c["accent"], c["accent2"], mix(c["accent2"], c["fg"], 0.4)]
    body = "gradient = 1\ngradient_count = 4\n" + "".join(f"gradient_color_{i + 1} = '{col}'\n" for i, col in enumerate(cols))
    text, parked = cava_split(f.read_text())
    parked += [ln.rstrip("\n") for ln in CAVA_ACTIVE.findall(text)]       # the user's own active gradient lines
    text = CAVA_ACTIVE.sub("", text)
    was = "".join(f"#was# {ln}\n" for ln in parked)
    if re.search(r"^\[color\]\s*$", text, re.M):
        blk = f"# >>> {MARK}\n{was}{body}# <<< {MARK}\n"
        text = re.sub(r"^(\[color\]\s*\n)", lambda m: m.group(1) + blk, text, count=1, flags=re.M)
    else:
        text = text.rstrip("\n") + f"\n\n# >>> {MARK}\n[color]\n{was}{body}# <<< {MARK}\n"
    write(f, text)
    run("pkill", "-USR2", "cava")


# ---------------------------------------------------------------- dark / light preference
def apply_scheme(c: dict[str, str]) -> None:
    run("gsettings", "set", "org.gnome.desktop.interface", "color-scheme", "prefer-dark" if lum(c["bg"]) < 0.5 else "prefer-light")


def apply_all(t: dict[str, Any], c: dict[str, str]) -> None:
    for fn in (lambda: apply_firefox(c, t["name"]), lambda: apply_yazi(t, c), lambda: apply_lodica(c),
               lambda: apply_kde(c, t["name"]), lambda: apply_micro(t, c), lambda: apply_cava(c), lambda: apply_scheme(c)):
        try:
            fn()
        except Exception as e:  # one app failing must never stop the others
            print(f"appthemes: {e}", flush=True)


# ---------------------------------------------------------------- undo (uninstall)
def unblock(path: pathlib.Path, comment: str) -> None:
    if not path.exists():
        return
    start, end = f"{comment} >>> {MARK}", f"{comment} <<< {MARK}"
    cur = path.read_text()
    new = re.sub(rf"\n*{re.escape(start)}.*?{re.escape(end)}\n?", "\n", cur, flags=re.S).strip("\n")
    if new:
        write(path, new + "\n")
    else:
        path.unlink()


def remove_all() -> None:
    """Take back everything the writers above added. Files that held only our content are removed."""
    y = CFG / "yazi"
    f = y / "theme.toml"
    if f.exists() and "Generated by hearthshell" in f.read_text():
        f.unlink()
        if (y / "theme.toml.pre-hearthshell").exists():
            (y / "theme.toml.pre-hearthshell").rename(f)
    for n in ("HearthshellA", "HearthshellB"):
        (HOME / ".local" / "share" / "color-schemes" / f"{n}.colors").unlink(missing_ok=True)
    for prof in firefox_profiles():
        chrome = prof / "chrome"
        for fname, imp in (("userChrome.css", "hearthshell.css"), ("userContent.css", "hearthshell-content.css")):
            (chrome / imp).unlink(missing_ok=True)
            uc = chrome / fname
            if uc.exists():
                rest = uc.read_text().replace(f'@import url("{imp}");\n', "")
                if rest.strip():
                    write(uc, rest)
                else:
                    uc.unlink()
        unblock(prof / "user.js", "//")
        try:
            chrome.rmdir()
        except OSError:
            pass
    (CFG / "micro" / "colorschemes" / "hearthshell.micro").unlink(missing_ok=True)
    ms = CFG / "micro" / "settings.json"
    try:
        data = json.loads(ms.read_text()) if ms.exists() else {}
        if data.get("colorscheme") == "hearthshell":
            del data["colorscheme"]
            if data:
                write(ms, json.dumps(data, indent=4) + "\n")
            else:
                ms.unlink()
    except (OSError, ValueError):
        pass
    cf = CFG / "cava" / "config"
    if cf.exists():
        text, parked = cava_split(cf.read_text())
        if parked and re.search(r"^\[color\]\s*$", text, re.M):
            text = re.sub(r"^(\[color\]\s*\n)", lambda m: m.group(1) + "".join(p + "\n" for p in parked), text, count=1, flags=re.M)
        write(cf, text)


if __name__ == "__main__":
    import sys
    if "--remove" in sys.argv:
        remove_all()
