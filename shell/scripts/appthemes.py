"""Theme the apps that are not part of the shell: Firefox, Yazi, Lodica, KDE/Qt apps, micro, cava, GTK dark/light.

Every writer is defensive: an app that is not installed is skipped, and a file the user wrote
themselves is never replaced (we only add an import line or a marked block).
"""
import json
import os
import pathlib
import re
import subprocess
from typing import Any

from themelib import bare, mix, rgb

HOME = pathlib.Path.home()
CFG = pathlib.Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config")
MARK = "hearthshell"


def write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def run(*cmd: str) -> None:
    try:
        subprocess.run(cmd, check=False, timeout=8, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        pass


def lum(c: str) -> float:
    r, g, b = rgb(c)
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255


def readable(c: str, bg: str) -> str:
    """Text colour that is legible on c."""
    return bg if lum(c) > 0.5 else "#ffffff" if lum(bg) > 0.5 else bg


def block(path: pathlib.Path, body: str, comment: str = "#") -> None:
    """Keep a marked block in a user-owned file, replacing only our own previous block."""
    start, end = f"{comment} >>> {MARK}", f"{comment} <<< {MARK}"
    cur = path.read_text() if path.exists() else ""
    cur = re.sub(rf"\n?{re.escape(start)}.*?{re.escape(end)}\n?", "\n", cur, flags=re.S).rstrip("\n")
    write(path, (cur + "\n\n" if cur else "") + f"{start}\n{body.rstrip()}\n{end}\n")


# ---------------------------------------------------------------- Firefox
def firefox_profiles() -> list[pathlib.Path]:
    out: list[pathlib.Path] = []
    for root in (CFG / "mozilla" / "firefox", HOME / ".mozilla" / "firefox",
                 HOME / ".var" / "app" / "org.mozilla.firefox" / ".mozilla" / "firefox"):
        if root.is_dir():
            out += [p.parent for p in root.glob("*/prefs.js")]
    return out


