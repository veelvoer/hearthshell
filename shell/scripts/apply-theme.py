#!/usr/bin/env python3
"""Apply a hearthshell theme to the rest of the desktop.

usage: apply-theme.py <theme-id> [json-options]

Writes generated theme files for kitty, rofi, fish, GTK, hyprlock, Hyprland and (appthemes.py) Firefox, Yazi, Lodica, KDE apps, micro and cava,
then reloads whatever can be reloaded live. Source of truth: ../themes.json.
A target is only written when its app is present (its config directory exists).
"""
import json
import os
import pathlib
import subprocess
import sys
from typing import Any

import appthemes
import fishvars
from themelib import Theme, bare, load_themes, mix, rgb

HOME = pathlib.Path.home()
CFG = pathlib.Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config")

DEFAULTS = {
    "gapsIn": 7, "gapsOut": 10, "rounding": 12, "borderSize": 2, "inactiveOpacity": 0.94,
    "blur": True, "blurSize": 6, "termOpacity": 0.92,
    "glassBar": False, "glassPanel": False, "glassLauncher": False, "glassTerminal": False, "glassAmount": 0.4,
    "accent": "", "motion": "normal", "shadow": True, "shadowSize": 12, "gradientBorder": True,
    "followMouse": True, "naturalScroll": True, "tapToClick": True, "pointerSpeed": 0.0,
    "repeatRate": 25, "repeatDelay": 600,
    "kittyFont": 11, "kittyPad": 12, "kittyCursor": "beam",
    "rofiWidth": 400, "rofiLines": 7, "rofiIcons": True,
    "syncKitty": True, "syncRofi": True, "syncFish": True, "syncGtk": True, "syncLock": True, "syncApps": True,
}


def write(path: str | pathlib.Path, text: str) -> None:
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def run(*cmd: str) -> str:
    """Run a command quietly and return its stdout ("" when it is missing or fails)."""
    try:
        out = subprocess.run(cmd, check=False, timeout=8, capture_output=True, text=True)
    except (OSError, subprocess.SubprocessError):
        return ""
    return out.stdout


def present(app_dir: str) -> bool:
    return (CFG / app_dir).is_dir()


Opt = dict[str, Any]


def derive(t: Theme) -> dict[str, str]:
    """Surfaces derived from the theme's base colours."""
    bg, fg = t["bg"], t["text"]
    return {
        "bg": bg, "fg": fg, "accent": t["wsa"], "accent2": t["icon"], "muted": t["wsti"], "line": t["wso"],
        "dim": bg, "surface": mix(bg, fg, 0.08), "surface2": mix(bg, fg, 0.18),
        "bright": mix(fg, "#ffffff", 0.35),
    }


def glass_alpha(opt: Opt) -> float:
    """Opacity of a frosted-glass surface: more glass amount, more see-through."""
    return max(0.35, 1.0 - float(opt["glassAmount"]))


def term_alpha(opt: Opt) -> float:
    return min(float(opt["termOpacity"]), glass_alpha(opt)) if opt["glassTerminal"] else float(opt["termOpacity"])


def apply_kitty(t: Theme, c: dict[str, str], opt: Opt) -> None:
    tm = t["term"]
    lines = [
        f"# Generated by hearthshell ({t['name']}). Do not edit.",
        f"background_opacity {term_alpha(opt):.2f}",
        f"font_size {float(opt['kittyFont']):.1f}",
        f"window_padding_width {int(opt['kittyPad'])}",
        f"cursor_shape {opt['kittyCursor']}",
        f"background {c['dim']}", f"foreground {c['fg']}",
        f"selection_background {c['line']}", f"selection_foreground {c['bright']}",
        f"url_color {tm['blue']}",
        f"cursor {c['accent2']}", f"cursor_text_color {c['dim']}",
        f"active_border_color {c['accent']}", f"inactive_border_color {c['line']}",
        f"mark1_foreground {c['dim']}", f"mark1_background {c['accent']}",
        f"mark2_foreground {c['dim']}", f"mark2_background {c['accent2']}",
        f"mark3_foreground {c['fg']}", f"mark3_background {c['line']}",
        f"active_tab_foreground {c['dim']}", f"active_tab_background {c['accent']}",
        f"inactive_tab_foreground {c['fg']}", f"inactive_tab_background {c['surface']}",
    ]
    hues = [tm[k] for k in ("red", "green", "yellow", "blue", "magenta", "cyan")]
    pal = [c["dim"], *hues, c["fg"]]
    brt = [c["surface2"], *hues, c["bright"]]
    lines += [f"color{i} {col}" for i, col in enumerate(pal)]
    lines += [f"color{i + 8} {col}" for i, col in enumerate(brt)]
    write(CFG / "kitty" / "hearthshell-theme.conf", "\n".join(lines) + "\n")
    run("pkill", "-USR1", "-x", "kitty")


def apply_rofi(t: Theme, c: dict[str, str], opt: Opt) -> None:
    r, g, b = rgb(c["dim"])
    ar, ag, ab = rgb(c["accent"])
    card = round(glass_alpha(opt) * 100) if opt["glassLauncher"] else 94
    write(CFG / "rofi" / "hearthshell-colors.rasi", f"""/* Generated by hearthshell ({t['name']}). Do not edit. */
* {{
    bg:        {c['dim']};
    fg:        {c['fg']};
    input-bg:  {c['surface']};
    muted:     {c['muted']};
    sel:       rgba({ar}, {ag}, {ab}, 14%);
    selborder: rgba({ar}, {ag}, {ab}, 40%);
    accent:    {c['accent']};
    card:      rgba({r}, {g}, {b}, {card}%);
    border:    {c['line']};
    qs-width:  {int(opt['rofiWidth'])}px;
    qs-lines:  {int(opt['rofiLines'])};
    qs-icons:  {'true' if opt['rofiIcons'] else 'false'};
}}
""")


def apply_gtk(t: Theme, c: dict[str, str]) -> None:
    names = {
        "accent_color": c["accent"], "accent_bg_color": c["accent"], "accent_fg_color": c["dim"],
        "window_bg_color": c["dim"], "window_fg_color": c["fg"],
        "view_bg_color": c["bg"], "view_fg_color": c["fg"],
        "headerbar_bg_color": c["dim"], "headerbar_fg_color": c["fg"], "headerbar_border_color": c["line"],
        "card_bg_color": c["bg"], "card_fg_color": c["fg"],
        "popover_bg_color": c["bg"], "popover_fg_color": c["fg"],
        "dialog_bg_color": c["dim"], "dialog_fg_color": c["fg"],
        "sidebar_bg_color": c["dim"], "sidebar_fg_color": c["fg"],
        "theme_bg_color": c["dim"], "theme_fg_color": c["fg"],
        "theme_base_color": c["bg"], "theme_text_color": c["fg"],
        "theme_selected_bg_color": c["accent"], "theme_selected_fg_color": c["dim"],
        "borders": c["line"], "link_color": c["accent2"],
    }
    css = f"/* Generated by hearthshell ({t['name']}). Do not edit. */\n"
    css += "".join(f"@define-color {k} {v};\n" for k, v in names.items())
    for d in ("gtk-3.0", "gtk-4.0"):
        if present(d):
            write(CFG / d / "hearthshell.css", css)


def apply_hyprlock(t: Theme, c: dict[str, str]) -> None:
    write(CFG / "hypr" / "hearthshell-hyprlock.conf", f"""# Generated by hearthshell ({t['name']}). Do not edit.
$qs_fg = rgb({bare(c['fg'])})
$qs_inner = rgb({bare(c['dim'])})
$qs_outer = rgb({bare(c['line'])})
$qs_accent = rgb({bare(c['accent'])})
""")


GLASS_RULE = (
    'QS_GLASS_BAR = QS_GLASS_BAR or hl.layer_rule({ name = "qs-glass-bar", '
    'match = { namespace = "^quickshell-bar$" }, blur = true, ignore_alpha = 0.2 })\n'
    'QS_GLASS_POPUP = QS_GLASS_POPUP or hl.layer_rule({ name = "qs-glass-popup", '
    'match = { namespace = "^quickshell-popup$" }, blur = true, ignore_alpha = 0.2 })\n'
    'QS_GLASS_SETTINGS = QS_GLASS_SETTINGS or hl.layer_rule({ name = "qs-glass-settings", '
    'match = { namespace = "^quickshell-settings$" }, blur = true, ignore_alpha = 0.2 })\n'
)


def lua_config(t: Theme, c: dict[str, str], opt: Opt) -> str:
    """Hyprland builds with the Lua config: one hl.config call plus the glass toggles."""
    grad = ",".join(f'"rgba({bare(col)}ff)"' for col in t["grad"])
    solid = f'"rgba({bare(t["grad"][0])}ff)"'
    active = f"{{colors={{{grad}}},angle=45}}" if opt["gradientBorder"] else solid
    shadow = bare(mix(c["bg"], "#000000", 0.5))
    size = int(opt["blurSize"])
    passes = max(1, min(4, round(size / 2)))
    tf = lambda k: "true" if opt[k] else "false"
    shadows = "true" if opt["shadow"] and int(opt["shadowSize"]) > 0 else "false"
    anims = "false" if opt["motion"] == "off" else "true"
    config = (
        "hl.config({"
        f"general={{gaps_in={int(opt['gapsIn'])},gaps_out={int(opt['gapsOut'])},border_size={int(opt['borderSize'])},"
        f"col={{active_border={active},inactive_border=\"rgba({bare(c['line'])}aa)\"}}}},"
        f"decoration={{rounding={int(opt['rounding'])},inactive_opacity={float(opt['inactiveOpacity']):.2f},"
        f"shadow={{enabled={shadows},range={max(1, int(opt['shadowSize']))},color=\"rgba({shadow}aa)\"}},"
        f"blur={{enabled={tf('blur')},size={size},passes={passes}}}}},"
        f"animations={{enabled={anims}}},"
        f"input={{follow_mouse={1 if opt['followMouse'] else 0},sensitivity={float(opt['pointerSpeed']):.2f},"
        f"repeat_rate={int(opt['repeatRate'])},repeat_delay={int(opt['repeatDelay'])},"
        f"touchpad={{natural_scroll={tf('naturalScroll')},tap_to_click={tf('tapToClick')}}}}}"
        "})\n"
    )
    toggle = (f"if QS_GLASS_BAR then QS_GLASS_BAR:set_enabled({tf('glassBar')}) end "
              f"if QS_GLASS_POPUP then QS_GLASS_POPUP:set_enabled({tf('glassPanel') if not opt['glassBar'] else 'true'}) end "
              f"if QS_GLASS_SETTINGS then QS_GLASS_SETTINGS:set_enabled({tf('glassPanel')}) end\n")
    return config + toggle + window_lua(opt)


def keyword_settings(t: Theme, c: dict[str, str], opt: Opt) -> list[tuple[str, str]]:
    """The same settings as hyprlang keywords (older, non-Lua Hyprland)."""
    grad = " ".join(f"rgba({bare(col)}ff)" for col in t["grad"])
    active = f"{grad} 45deg" if opt["gradientBorder"] else f"rgba({bare(t['grad'][0])}ff)"
    size = int(opt["blurSize"])
    yn = lambda k: "true" if opt[k] else "false"
    shadows = "true" if opt["shadow"] and int(opt["shadowSize"]) > 0 else "false"
    return [
        ("general:gaps_in", str(int(opt["gapsIn"]))), ("general:gaps_out", str(int(opt["gapsOut"]))),
        ("general:border_size", str(int(opt["borderSize"]))),
        ("general:col.active_border", active), ("general:col.inactive_border", f"rgba({bare(c['line'])}aa)"),
        ("decoration:rounding", str(int(opt["rounding"]))),
        ("decoration:inactive_opacity", f"{float(opt['inactiveOpacity']):.2f}"),
        ("decoration:shadow:enabled", shadows), ("decoration:shadow:range", str(max(1, int(opt["shadowSize"])))),
        ("decoration:shadow:color", f"rgba({bare(mix(c['bg'], '#000000', 0.5))}aa)"),
        ("decoration:blur:enabled", yn("blur")), ("decoration:blur:size", str(size)),
        ("decoration:blur:passes", str(max(1, min(4, round(size / 2))))),
        ("animations:enabled", "false" if opt["motion"] == "off" else "true"),
        ("input:follow_mouse", "1" if opt["followMouse"] else "0"),
        ("input:sensitivity", f"{float(opt['pointerSpeed']):.2f}"),
        ("input:repeat_rate", str(int(opt["repeatRate"]))), ("input:repeat_delay", str(int(opt["repeatDelay"]))),
        ("input:touchpad:natural_scroll", yn("naturalScroll")), ("input:touchpad:tap-to-click", yn("tapToClick")),
    ]


def hyprlang_file(settings: list[tuple[str, str]]) -> str:
    """A `source`-able hyprlang fragment with the same settings, grouped into sections."""
    lines = ["# Generated by hearthshell. Do not edit."]
    sections: dict[str, list[tuple[str, str]]] = {}
    for key, val in settings:
        parts = key.split(":")
        sections.setdefault(":".join(parts[:-1]), []).append((parts[-1], val))
    for path, items in sections.items():
        parts = path.split(":")
        for depth, name in enumerate(parts):
            lines.append("    " * depth + f"{name} {{")
        for name, val in items:
            lines.append("    " * len(parts) + f"{name} = {val}")
        for depth in range(len(parts) - 1, -1, -1):
            lines.append("    " * depth + "}")
    return "\n".join(lines) + "\n"


# Frosted app windows: groups of window classes that get a see-through window over the blurred backdrop.
# (?i) makes the match case-insensitive; flatpak ids and plain names are both listed.
WINDOW_GROUPS = {
    "glassBrowsers": r"^(?i)(firefox|org\.mozilla\.firefox|lodica|chromium|google-chrome|brave-browser|zen|zen-browser|librewolf)$",
    "glassFiles": r"^(?i)(org\.kde\.dolphin|dolphin|org\.gnome\.nautilus|nautilus|thunar|pcmanfm.*|nemo)$",
    "glassEditors": r"^(?i)(code|code-oss|vscodium|org\.kde\.kate|kate|org\.kde\.kwrite|org\.gnome\.gedit|org\.gnome\.texteditor)$",
    "glassChat": r"^(?i)(discord|vesktop|spotify|telegram.*|org\.telegram.*|signal|hearth|element|slack)$",
    "glassOther": r"^(?i)(org\.kde\.(okular|gwenview|ark|spectacle|kcalc|systemsettings|kinfocenter|konsole)|systemsettings|org\.gnome\.(calculator|evince|eog|loupe|papers|settings|baobab))$",
}


def window_lua(opt: Opt) -> str:
    """Lua that switches the frosted-window rules to the current settings. A rule is created once per group and
    opacity step and only toggled afterwards, so applying a theme over and over never piles up rules."""
    alpha = max(0.65, 1.0 - float(opt["glassAmount"]) * 0.6)
    step = round(alpha * 20) / 20
    inactive = max(0.6, step - 0.05)
    lines = [
        "QS_WIN = QS_WIN or {}",
        "for _, h in pairs(QS_WIN) do h:set_enabled(false) end",
        "local function qsw(key, cls, op) local h = QS_WIN[key .. op]; "
        "if not h then h = hl.window_rule({ name = 'qs-win-' .. key .. op, match = { class = cls }, opacity = op }); QS_WIN[key .. op] = h end; "
        "h:set_enabled(true) end",
    ]
    if opt.get("glassWindows") and opt["blur"]:
        for key, cls in WINDOW_GROUPS.items():
            if opt.get(key, True):
                lines.append(f"qsw('{key}', [[{cls}]], '{step:.2f} {inactive:.2f}')")
    return " ".join(lines) + "\n"


def apply_hyprland(t: Theme, c: dict[str, str], opt: Opt) -> None:
    lua = (CFG / "hypr" / "hyprland.lua").exists()
    if lua:
        body = lua_config(t, c, opt)
        write(CFG / "hypr" / "hearthshell-theme.lua", "-- Generated by hearthshell. Do not edit.\n" + GLASS_RULE + body)
        run("hyprctl", "eval", body.strip().replace("\n", " "))
        return
    settings = keyword_settings(t, c, opt)
    if present("hypr"):
        write(CFG / "hypr" / "hearthshell-theme.conf", hyprlang_file(settings))
    batch = " ; ".join(f"keyword {k} {v}" for k, v in settings)
    run("hyprctl", "--batch", batch)


def apply_fish(t: Theme, c: dict[str, str]) -> None:
    """Universal variables update every running fish shell immediately."""
    tm = t["term"]
    bg, fg, line = c["bg"], c["fg"], bare(c["line"])
    sets = {
        "qs_pill": c["surface"], "qs_git": c["line"], "qs_fg": fg, "qs_aqua": c["accent2"],
        "qs_green": c["accent"], "qs_amber": tm["yellow"], "qs_red": tm["red"],
        "fish_color_normal": fg, "fish_color_command": c["accent"], "fish_color_keyword": tm["magenta"],
        "fish_color_quote": tm["yellow"], "fish_color_redirection": tm["cyan"],
        "fish_color_end": tm["magenta"], "fish_color_error": tm["red"],
        "fish_color_param": fg, "fish_color_comment": mix(bg, fg, 0.45),
        "fish_color_operator": tm["cyan"], "fish_color_escape": tm["magenta"],
        "fish_color_autosuggestion": mix(bg, fg, 0.4), "fish_color_cwd": c["accent"],
        "fish_color_match": c["accent2"], "fish_pager_color_prefix": c["accent2"],
        "fish_pager_color_completion": fg, "fish_pager_color_description": mix(bg, fg, 0.5),
        "fish_pager_color_progress": c["accent"],
    }
    fishvars.backup([*sets, "fish_color_valid_path", "fish_color_selection", "fish_color_search_match",
                     "fish_pager_color_selected_background"])
    cmds = [f"set -U {k} {bare(v)}" for k, v in sets.items()]
    cmds += [
        f"set -U fish_color_valid_path {bare(fg)} --underline",
        f"set -U fish_color_selection {bare(fg)} --background={line}",
        f"set -U fish_color_search_match --background={line}",
        f"set -U fish_pager_color_selected_background --background={line}",
    ]
    run("fish", "-c", "; ".join(cmds))


def main() -> None:
    themes = load_themes()
    tid = sys.argv[1] if len(sys.argv) > 1 else "everforest"
    if tid not in themes:
        sys.exit(f"unknown theme: {tid}")
    opt: Opt = dict(DEFAULTS)
    if len(sys.argv) > 2:
        opt.update(json.loads(sys.argv[2]))
    t = themes[tid]
    acc = str(opt.get("accent") or "")
    if acc:
        t = {**t, "wsa": acc, "icon": acc,
             "grad": [bare(acc), bare(mix(acc, "#ffffff", 0.3)), bare(mix(acc, t["bg"], 0.35))]}
    c = derive(t)

    if opt["syncKitty"] and present("kitty"):
        apply_kitty(t, c, opt)
    if opt["syncRofi"] and present("rofi"):
        apply_rofi(t, c, opt)
    if opt["syncGtk"]:
        apply_gtk(t, c)
    if opt["syncLock"] and present("hypr"):
        apply_hyprlock(t, c)
    apply_hyprland(t, c, opt)
    if opt["syncFish"] and present("fish"):
        apply_fish(t, c)
    if opt["syncApps"]:
        appthemes.apply_all(t, c)


if __name__ == "__main__":
    main()
